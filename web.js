function injectSearchBar() {
  const categoriesDiv = document.getElementById("categories")
  if (!categoriesDiv) return

  const wrapper = document.createElement("div")
  wrapper.id = "searchWrapper"
  Object.assign(wrapper.style, {
    display: "flex",
    flexDirection: "column",
    alignItems: "center",
    margin: "0 0 2rem 0",
    padding: "0 1rem",
  })

  wrapper.innerHTML = `
    <div style="position:relative;width:100%;max-width:520px;">
      <span style="position:absolute;left:1.1rem;top:50%;transform:translateY(-50%);font-size:1.1rem;pointer-events:none;user-select:none;">🔍</span>
      <input
        id="toolSearchInput"
        type="text"
        placeholder="Search AI tools... (e.g. 'image', 'free', 'video')"
        autocomplete="off"
        style="
          width:100%;
          padding:0.85rem 3rem 0.85rem 2.8rem;
          border-radius:30px;
          border:2px solid rgba(139,92,246,0.35);
          background:rgba(139,92,246,0.08);
          color:#e4e8f0;
          font-size:1rem;
          font-family:inherit;
          outline:none;
          transition:border-color 0.3s, box-shadow 0.3s, background 0.3s;
        "
      />
      <button id="searchClearBtn" title="Clear search" style="
        position:absolute;right:1rem;top:50%;transform:translateY(-50%);
        background:none;border:none;color:#6b7280;cursor:pointer;
        font-size:1.1rem;display:none;transition:color 0.2s;
      ">✕</button>
    </div>
    <div id="searchResultCount" style="
      text-align:center;font-size:0.88rem;color:#8b5cf6;
      margin-top:0.6rem;display:none;
    "></div>
  `

  categoriesDiv.parentNode.insertBefore(wrapper, categoriesDiv)

  const input    = document.getElementById("toolSearchInput")
  const clearBtn = document.getElementById("searchClearBtn")
  const countEl  = document.getElementById("searchResultCount")

  // Focus glow styles
  input.addEventListener("focus", () => {
    input.style.borderColor = "#8b5cf6"
    input.style.boxShadow   = "0 0 0 4px rgba(139,92,246,0.15)"
    input.style.background  = "rgba(139,92,246,0.13)"
  })
  input.addEventListener("blur", () => {
    input.style.borderColor = "rgba(139,92,246,0.35)"
    input.style.boxShadow   = "none"
    input.style.background  = "rgba(139,92,246,0.08)"
  })

  // Live search on every keystroke
  input.addEventListener("input", () => {
    const query = input.value.trim().toLowerCase()
    clearBtn.style.display = query ? "block" : "none"
    runSearch(query)
  })

  // Clear button resets to active category
  clearBtn.addEventListener("click", () => {
    input.value = ""
    clearBtn.style.display = "none"
    countEl.style.display  = "none"
    const activeCat = document.querySelector(".category-btn.active")?.dataset.category || "all"
    filterTools(activeCat)
    document.querySelectorAll(".category-btn").forEach((b) => {
      b.style.opacity = "1"; b.style.pointerEvents = "auto"
    })
    input.focus()
  })

  function runSearch(query) {
    const cards = document.querySelectorAll(".tool-card")
    if (!query) {
      const activeCat = document.querySelector(".category-btn.active")?.dataset.category || "all"
      filterTools(activeCat)
      countEl.style.display = "none"
      document.querySelectorAll(".category-btn").forEach((b) => {
        b.style.opacity = "1"; b.style.pointerEvents = "auto"
      })
      return
    }

    // Dim category buttons while searching
    document.querySelectorAll(".category-btn").forEach((b) => {
      b.style.opacity = "0.4"; b.style.pointerEvents = "none"
    })

    let matched = 0
    cards.forEach((card) => {
      const toolId = card.dataset.tool
      const tool   = toolsData[toolId]
      if (!tool) { card.style.display = "none"; return }

      const haystack = [
        tool.name, tool.category, tool.pricing,
        tool.bestFor, card.querySelector("p")?.textContent || ""
      ].join(" ").toLowerCase()

      const words   = query.split(/\s+/).filter(Boolean)
      const isMatch = words.every((w) => haystack.includes(w))
      card.style.display = isMatch ? "block" : "none"
      if (isMatch) matched++
    })

    const q = input.value.trim()
    countEl.textContent = matched > 0
      ? `✅ ${matched} tool${matched !== 1 ? "s" : ""} found for "${q}"`
      : `❌ No tools found for "${q}" — try another keyword`
    countEl.style.color   = matched > 0 ? "#8b5cf6" : "#ec4899"
    countEl.style.display = "block"
  }
}

