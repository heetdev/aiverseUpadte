// ── KEYBOARD EVENTS ──────────────────────────────────────────
let focusedCardIndex = -1
const getVisibleCards = () =>
  [...document.querySelectorAll(".tool-card")].filter((c) => c.style.display !== "none")

document.addEventListener("keydown", (e) => {
  const detailActive = document.getElementById("detailPage").classList.contains("active")
  const aboutActive  = document.getElementById("aboutPage").classList.contains("active")

  // Escape → go back to main page
  if (e.key === "Escape") {
    if (detailActive || aboutActive) {
      showMainPage()
      focusedCardIndex = -1
    }
    return
  }

  // '/' → focus search / first card (shortcut hint)
  if (e.key === "/" && !detailActive && !aboutActive) {
    e.preventDefault()
    showToast("⌨️ Use ← → to browse cards, Enter to open, Esc to go back")
    focusedCardIndex = 0
    highlightCard(focusedCardIndex)
    return
  }

  if (detailActive || aboutActive) return

  const cards = getVisibleCards()
  if (!cards.length) return

  // Arrow navigation
  if (e.key === "ArrowRight" || e.key === "ArrowDown") {
    e.preventDefault()
    focusedCardIndex = (focusedCardIndex + 1) % cards.length
    highlightCard(focusedCardIndex, cards)
  } else if (e.key === "ArrowLeft" || e.key === "ArrowUp") {
    e.preventDefault()
    focusedCardIndex = (focusedCardIndex - 1 + cards.length) % cards.length
    highlightCard(focusedCardIndex, cards)
  } else if (e.key === "Enter" && focusedCardIndex >= 0) {
    cards[focusedCardIndex].click()
  }

  // Number keys 1-7 → switch categories
  const catKeys = ["all","website","image","video","text","audio","code","productivity"]
  const num = parseInt(e.key)
  if (num >= 1 && num <= 7) {
    const cat = catKeys[num]
    const btn = document.querySelector(`.category-btn[data-category="${cat}"]`)
    if (btn) { btn.click(); focusedCardIndex = -1 }
  }
})

function highlightCard(idx, cards) {
  cards = cards || getVisibleCards()
  cards.forEach((c, i) => {
    c.style.outline = i === idx ? "3px solid #8b5cf6" : "none"
    c.style.outlineOffset = "3px"
  })
  cards[idx]?.scrollIntoView({ behavior: "smooth", block: "nearest" })
}

